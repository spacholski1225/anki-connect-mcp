import { z } from 'zod';
import { READ_ONLY, additive, defineTool, destructive, type ToolDefinition } from './define.js';

/** Tools that drive the Anki desktop window. They need a user at the screen, so they are opt-in. */
export const guiTools: ToolDefinition[] = [
    defineTool({
        name: 'gui_browse',
        title: 'Open card browser',
        description: 'Opens the Anki Browser window with the given search query and returns the card IDs it shows.',
        inputSchema: { query: z.string().describe('Anki search query, e.g. `deck:"My Deck" is:due`.') },
        annotations: additive(true),
        handler: ({ query }, anki) => anki.invoke('guiBrowse', { query }),
    }),
    defineTool({
        name: 'gui_add_cards',
        title: 'Open Add Cards dialog',
        description: 'Opens the Anki "Add" dialog for the user. Does not add anything by itself; use add_note to add notes directly.',
        inputSchema: {},
        annotations: additive(false),
        handler: (_args, anki) => anki.invoke('guiAddCards'),
    }),
    defineTool({
        name: 'gui_current_card',
        title: 'Current review card',
        description: 'Returns information about the card currently shown in the Anki reviewer (question, answer, buttons, deck, IDs), or null if the reviewer is not open.',
        inputSchema: {},
        annotations: READ_ONLY,
        handler: (_args, anki) => anki.invoke('guiCurrentCard'),
    }),
    defineTool({
        name: 'gui_start_card_timer',
        title: 'Start card timer',
        description: 'Restarts the answer timer of the card currently in the reviewer. Returns true on success.',
        inputSchema: {},
        annotations: additive(true),
        handler: (_args, anki) => anki.invoke('guiStartCardTimer'),
    }),
    defineTool({
        name: 'gui_show_question',
        title: 'Show question',
        description: 'Shows the question side of the current card in the reviewer. Returns true if the reviewer is open.',
        inputSchema: {},
        annotations: additive(true),
        handler: (_args, anki) => anki.invoke('guiShowQuestion'),
    }),
    defineTool({
        name: 'gui_show_answer',
        title: 'Show answer',
        description: 'Shows the answer side of the current card in the reviewer. Returns true if the reviewer is open.',
        inputSchema: {},
        annotations: additive(true),
        handler: (_args, anki) => anki.invoke('guiShowAnswer'),
    }),
    defineTool({
        name: 'gui_answer_card',
        title: 'Answer current card',
        description: 'Answers the card currently in the reviewer, which updates its scheduling. The answer must be shown first (gui_show_answer). Returns true on success.',
        inputSchema: { ease: z.number().int().min(1).max(4).describe('Answer ease: 1=Again, 2=Hard, 3=Good, 4=Easy.') },
        annotations: additive(false),
        handler: ({ ease }, anki) => anki.invoke('guiAnswerCard', { ease }),
    }),
    defineTool({
        name: 'gui_deck_overview',
        title: 'Open deck overview',
        description: 'Opens the overview screen of the given deck in Anki. Returns true on success.',
        inputSchema: { name: z.string().describe('Deck name.') },
        annotations: additive(true),
        handler: ({ name }, anki) => anki.invoke('guiDeckOverview', { name }),
    }),
    defineTool({
        name: 'gui_deck_browser',
        title: 'Open deck list',
        description: 'Opens the main deck list screen in Anki.',
        inputSchema: {},
        annotations: additive(true),
        handler: (_args, anki) => anki.invoke('guiDeckBrowser'),
    }),
    defineTool({
        name: 'gui_deck_review',
        title: 'Start deck review',
        description: 'Starts a review session of the given deck in Anki. Returns true on success.',
        inputSchema: { name: z.string().describe('Deck name.') },
        annotations: additive(true),
        handler: ({ name }, anki) => anki.invoke('guiDeckReview', { name }),
    }),
    defineTool({
        name: 'gui_exit_anki',
        title: 'Quit Anki',
        description: 'Closes the Anki application. After this every tool fails until the user starts Anki again. Only call when the user asks for it.',
        inputSchema: {},
        annotations: destructive(true),
        handler: (_args, anki) => anki.invoke('guiExitAnki'),
    }),
];
